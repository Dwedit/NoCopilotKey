int my_strnicmp(const wchar_t* str1, const char* str2, int limit)
{
	int i;
	for (i = 0; i < limit; i++)
	{
		int c = str1[i];
		if (c >= 'a' && c <= 'z')
		{
			c -= 0x20;
		}
		int c2 = str2[i];
		if (c2 >= 'a' && c2 <= 'z')
		{
			c2 -= 0x20;
		}
		if (c != c2)
		{
			return c - c2;
		}
		if (c == 0) break;
	}
	return 0;
}

int VKeyNameToKeyCode(const wchar_t* keyName)
{
	int len = wcslen(keyName);
	if (0 == my_strnicmp(keyName, "VK_", 3))
	{
		keyName += 3;
		len -= 3;
	}

	if (len == 0) return 0;
	for (int keyIndex = 0; keyIndex < ARRAYSIZE(vkeyNamesTable); keyIndex++)
	{
		const char* tableKeyName = vkeyNamesTable[keyIndex];
		if (0 == my_strnicmp(keyName, tableKeyName, len + 1))
		{
			return keyIndex;
		}
	}
	return 0;
}
